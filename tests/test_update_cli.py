import hashlib
import json
import os
import shutil
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path


REPOSITORY_ROOT = Path(__file__).resolve().parents[1]
CLI_PATH = REPOSITORY_ROOT / "hulotte.py"
ADAPTER_HPP = "src/custom/Decoder_hw.hpp"
ADAPTER_CPP = "src/custom/Decoder_hw.cpp"


class UpdateTests(unittest.TestCase):
    def run_cli(self, *arguments, stdin=None):
        return subprocess.run([sys.executable, str(CLI_PATH), *arguments], input=stdin,
                              capture_output=True, text=True, timeout=60)

    def make_project(self, directory: Path) -> Path:
        project_dir = directory / "project"
        for arguments in (
            ("init", str(project_dir)),
            ("module", "add", str(project_dir), "--type", "verilator", "--name", "Decoder_hw", "--yes",
             "--in-type", "int8_t", "--in-width", "6", "--in-lanes", "7", "--out-type", "int16_t",
             "--out-width", "3", "--out-lanes", "4", "--out-unsigned"),
            ("module", "add", str(project_dir), "--type", "cfunction", "--name", "Filter_c", "--yes",
             "--in-type", "float", "--out-type", "double"),
            ("module", "add", str(project_dir), "--type", "custom", "--name", "Gain", "--yes"),
        ):
            result = self.run_cli(*arguments)
            self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
        return project_dir

    def age(self, project_dir: Path, relative: str) -> str:
        """Make a file look as written by an older Hulotte: remove a line and record that content."""
        path = project_dir / relative
        old = path.read_text().replace("#include <vector>\n", "", 1)
        if old == path.read_text():
            old = path.read_text() + "# older template\n"
        path.write_text(old)
        registry_path = project_dir / ".hulotte/generated.json"
        registry = json.loads(registry_path.read_text())
        registry["files"][relative]["sha256"] = hashlib.sha256(old.encode()).hexdigest()
        registry_path.write_text(json.dumps(registry))
        return old

    def test_generation_records_only_the_files_hulotte_owns(self):
        with tempfile.TemporaryDirectory() as temporary_directory:
            project_dir = self.make_project(Path(temporary_directory))
            registry = json.loads((project_dir / ".hulotte/generated.json").read_text())
            self.assertEqual(sorted(registry["files"]), [
                "CMakeLists.txt", "src/custom/Decoder_hw.cpp", "src/custom/Decoder_hw.hpp",
                "src/custom/Filter_c.cpp", "src/custom/Filter_c.hpp"])

    def test_fresh_project_is_up_to_date(self):
        with tempfile.TemporaryDirectory() as temporary_directory:
            project_dir = self.make_project(Path(temporary_directory))
            result = self.run_cli("update", str(project_dir), "--check")
            self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
            self.assertIn("CMakeLists.txt: up to date", result.stdout)
            self.assertIn(f"{ADAPTER_HPP}: up to date", result.stdout)
            self.assertIn("src/custom/Filter_c.hpp: up to date", result.stdout)
            self.assertNotIn("Gain", result.stdout)
            result = self.run_cli("update", str(project_dir), "--yes")
            self.assertEqual(result.returncode, 0)
            self.assertIn("Nothing to update.", result.stdout)

    def test_outdated_files_are_rewritten_and_user_files_are_not_touched(self):
        with tempfile.TemporaryDirectory() as temporary_directory:
            project_dir = self.make_project(Path(temporary_directory))
            expected = (project_dir / ADAPTER_HPP).read_text()
            expected_cpp = (project_dir / ADAPTER_CPP).read_text()
            self.age(project_dir, ADAPTER_HPP)
            user_files = ["src/main.cpp", "src/hw/Decoder_hw.sv", "src/custom/filter_c_impl.c",
                          "src/custom/filter_c_api.h", "src/custom/Gain.hpp", "src/custom/Gain.cpp", "README.md"]
            for relative in user_files:
                path = project_dir / relative
                path.write_text(path.read_text() + "// edited by the user\n")

            result = self.run_cli("update", str(project_dir), "--check")
            self.assertEqual(result.returncode, 1)
            self.assertIn(f"{ADAPTER_HPP}: will be updated", result.stdout)

            result = self.run_cli("update", str(project_dir), "--yes")
            self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
            self.assertIn(f"Updated: {ADAPTER_HPP}", result.stdout)
            # The interface read back gives exactly the adapter generated by module add.
            self.assertEqual((project_dir / ADAPTER_HPP).read_text(), expected)
            self.assertEqual((project_dir / ADAPTER_CPP).read_text(), expected_cpp)
            self.assertFalse((project_dir / (ADAPTER_HPP + ".orig")).exists())
            for relative in user_files:
                self.assertTrue((project_dir / relative).read_text().endswith("// edited by the user\n"), relative)
            self.assertEqual(self.run_cli("update", str(project_dir), "--check").returncode, 0)

    def test_files_edited_by_hand_need_force_and_keep_a_copy(self):
        with tempfile.TemporaryDirectory() as temporary_directory:
            project_dir = self.make_project(Path(temporary_directory))
            expected = (project_dir / "CMakeLists.txt").read_text()
            self.age(project_dir, "CMakeLists.txt")
            edited = (project_dir / "CMakeLists.txt").read_text() + "# my change\n"
            (project_dir / "CMakeLists.txt").write_text(edited)

            result = self.run_cli("update", str(project_dir), "--yes")
            self.assertEqual(result.returncode, 1)
            self.assertIn("CMakeLists.txt: EDITED BY HAND", result.stdout)
            self.assertIn("-# my change", result.stdout)
            self.assertIn("Skipped (edited by hand, use --force): CMakeLists.txt", result.stdout)
            self.assertEqual((project_dir / "CMakeLists.txt").read_text(), edited)

            result = self.run_cli("update", str(project_dir), "--yes", "--force")
            self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
            self.assertEqual((project_dir / "CMakeLists.txt").read_text(), expected)
            self.assertEqual((project_dir / "CMakeLists.txt.orig").read_text(), edited)

    def test_project_without_registry_shows_the_diff_and_asks(self):
        with tempfile.TemporaryDirectory() as temporary_directory:
            project_dir = self.make_project(Path(temporary_directory))
            shutil.rmtree(project_dir / ".hulotte")
            hpp = project_dir / ADAPTER_HPP
            expected = hpp.read_text()
            hpp.write_text(expected.replace("#include <vector>\n", ""))

            result = self.run_cli("update", str(project_dir), stdin="n\n")
            self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
            self.assertIn("not recorded as generated: check the diff", result.stdout)
            self.assertIn("+#include <vector>", result.stdout)
            self.assertIn("Cancelled; no files were changed.", result.stdout)
            self.assertNotEqual(hpp.read_text(), expected)

            result = self.run_cli("update", str(project_dir), stdin="y\n")
            self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
            self.assertEqual(hpp.read_text(), expected)
            self.assertTrue((project_dir / (ADAPTER_HPP + ".orig")).is_file())
            registry = json.loads((project_dir / ".hulotte/generated.json").read_text())
            self.assertIn("CMakeLists.txt", registry["files"])
            self.assertEqual(self.run_cli("update", str(project_dir), "--check").returncode, 0)

    @unittest.skipUnless(
        os.environ.get("HULOTTE_TEST_STREAMPU_ROOT") and shutil.which("verilator") and shutil.which("cmake"),
        "Set HULOTTE_TEST_STREAMPU_ROOT and install CMake/Verilator to run the update build test",
    )
    def test_updated_old_project_builds_and_marks_its_check(self):
        with tempfile.TemporaryDirectory() as temporary_directory:
            project_dir = Path(temporary_directory) / "legacy"
            for arguments in (("init", str(project_dir)),
                              ("module", "add", str(project_dir), "--type", "verilator", "--name", "Echo_hw", "--yes")):
                self.assertEqual(self.run_cli(*arguments).returncode, 0)
            # An older project: no registry, no RTL hash in CMake, no mark_verified in the adapter.
            shutil.rmtree(project_dir / ".hulotte")
            cmake = project_dir / "CMakeLists.txt"
            text = cmake.read_text()
            start = text.index("    # SHA-256 of the RTL sources")
            end = text.index("    if(DEFINED ENV{VERILATOR_ROOT})")
            cmake.write_text(text[:start] + text[end:])

            main_path = project_dir / "src/main.cpp"
            main_cpp = main_path.read_text()
            main_cpp = main_cpp.replace('#include "Pass_through.hpp"', '#include "custom/Echo_hw.hpp"')
            main_cpp = main_cpp.replace("spu::module::Pass_through pass_through(frame_size);",
                                        "hulotte::module::Echo_hw pass_through(frame_size);")
            main_cpp = main_cpp.replace('pass_through["process::in"]', 'pass_through["simulate::input"]')
            main_cpp = main_cpp.replace('pass_through["process::out"]', 'pass_through["simulate::output"]')
            main_cpp = main_cpp.replace('    std::cout << "[PASS] No mismatches over "',
                                        '    pass_through.mark_verified("smoke");\n    std::cout << "[PASS] No mismatches over "')
            main_path.write_text(main_cpp)

            def run(*command):
                return subprocess.run(command, capture_output=True, text=True, timeout=300, cwd=project_dir)
            def build_and_run():
                for command in (("cmake", "-S", str(project_dir), "-B", str(project_dir / "build"),
                                 "-DSTREAMPU_ROOT=" + os.environ["HULOTTE_TEST_STREAMPU_ROOT"]),
                                ("cmake", "--build", str(project_dir / "build"), "--parallel", "2"),
                                (str(project_dir / "build/legacy"),)):
                    result = run(*command)
                    if result.returncode != 0:
                        return result
                return result

            result = build_and_run()
            self.assertNotEqual(result.returncode, 0)
            self.assertIn("mark_verified() needs the RTL hash", result.stdout + result.stderr)

            result = self.run_cli("update", str(project_dir), "--yes")
            self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
            self.assertIn("Updated: CMakeLists.txt", result.stdout)
            shutil.rmtree(project_dir / "build")
            result = build_and_run()
            self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
            self.assertTrue((project_dir / "synth/verified/Echo_hw.yml").is_file())


if __name__ == "__main__":
    unittest.main()
